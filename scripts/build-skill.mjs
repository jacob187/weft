#!/usr/bin/env node
/**
 * Generate the weft skill's style references from the templates (single source of truth).
 *
 *   npm run build:skill
 *
 * Writes:
 *   skills/weft/references/index.json          compact catalog used by `weft.mjs list|deal`
 *   skills/weft/references/styles/<slug>.md    one reference per template
 *
 * Requires Node ≥ 22.18 (imports meta.ts via built-in type stripping).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const templatesDir = join(root, 'src/templates');
const outDir = join(root, 'skills/weft/references');
const stylesDir = join(outDir, 'styles');

/** Family names from a Google Fonts css2 URL. */
function fontFamilies(href) {
  if (!href) return [];
  return [...href.matchAll(/family=([^:&]+)/g)].map((m) => decodeURIComponent(m[1].replace(/\+/g, ' ')));
}

/** Exported functions/classes of an effect module with the JSDoc block directly above each. */
function effectExports(src) {
  const out = [];
  const re = /(\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*)?export (?:async )?(function|class|const) (\w+)(\([^)]*\))?/g;
  for (const m of src.matchAll(re)) {
    const doc = (m[2] ?? '')
      .split('\n')
      .map((l) => l.replace(/^\s*\* ?/, '').trim())
      .filter(Boolean)
      .join(' ');
    out.push({ name: m[4], sig: m[5] ?? '', doc });
  }
  return out;
}

/** content.ts up to (not including) the demo object: interfaces + JSDoc. */
function contentModel(src) {
  const cut = src.search(/^export const demo\b/m);
  return (cut === -1 ? src : src.slice(0, cut))
    .replace(/^import .*\n/gm, '')
    .trim();
}

const slugs = readdirSync(templatesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(templatesDir, d.name, 'Template.astro')))
  .map((d) => d.name);

rmSync(stylesDir, { recursive: true, force: true });
mkdirSync(stylesDir, { recursive: true });

const index = [];
for (const slug of slugs) {
  const dir = join(templatesDir, slug);
  const meta = (await import(pathToFileURL(join(dir, 'meta.ts')).href)).default;
  const theme = readFileSync(join(dir, 'theme.css'), 'utf8').trim();
  const content = readFileSync(join(dir, 'content.ts'), 'utf8');
  const files = readdirSync(dir).sort();
  const effects = files
    .filter((f) => f.endsWith('.ts') && !['meta.ts', 'content.ts'].includes(f))
    .map((f) => ({ file: f, exports: effectExports(readFileSync(join(dir, f), 'utf8')) }));
  const fonts = fontFamilies(meta.fontsHref);
  const usesThree = effects.some((e) => /from 'three/.test(readFileSync(join(dir, e.file), 'utf8')));

  index.push({
    slug,
    no: meta.no,
    name: meta.name,
    summary: meta.summary,
    technique: meta.technique,
    tags: meta.tags ?? [],
    bestFor: meta.bestFor ?? [],
    swatch: meta.swatch,
    fonts,
    three: usesThree,
  });

  const title = meta.no ? `${meta.name} (${meta.no} · ${slug})` : `${meta.name} (${slug})`;
  const md = `<!-- Generated by scripts/build-skill.mjs from src/templates/${slug}/. Do not edit by hand. -->
# ${title}

${meta.summary}

- **Technique:** ${meta.technique}
- **Tags:** ${(meta.tags ?? []).join(', ')}
- **Best for:** ${(meta.bestFor ?? []).join('; ')}
- **Fonts:** ${fonts.join(', ') || 'system'}${meta.fontsHref ? `\n- **Fonts href:** \`${meta.fontsHref}\`` : ''}
- **Swatch:** ${meta.swatch.join(' · ')}
- **Dependencies:** ${usesThree ? '`three` (npm)' : 'none beyond the shared helpers'}
- **Source:** \`src/templates/${slug}/\` (${files.join(', ')})

## Tokens — \`theme.css\`
Every color and font stack the design uses. Override per site; canvas/WebGL effects read these at init.

\`\`\`css
${theme}
\`\`\`

## Signature effects
${
  effects.length
    ? effects
        .map(
          (e) =>
            `- \`${e.file}\`` +
            (e.exports.length
              ? '\n' + e.exports.map((x) => `  - \`${x.name}${x.sig}\`${x.doc ? ` — ${x.doc}` : ''}`).join('\n')
              : ''),
        )
        .join('\n')
    : '- None (pure CSS/markup).'
}

## Content model — \`content.ts\`
Every user-visible string lives here. Fields ending in \`Html\` are trusted inline HTML (\`<em> <b> <i> <br> <a> <span>\`).

\`\`\`ts
${contentModel(content)}
\`\`\`

## Use it
- Full site: \`node <skill-dir>/scripts/weft.mjs template ${slug} --out <dir>\`
- Style kit for an existing project: \`node <skill-dir>/scripts/weft.mjs style ${slug} --out <dir>\`
- Read \`src/templates/${slug}/style.css\` and \`Template.astro\` (from the plugin root) for exact component styling and markup.
`;
  writeFileSync(join(stylesDir, `${slug}.md`), md);
}

index.sort((a, b) => (a.no || '99').localeCompare(b.no || '99') || a.slug.localeCompare(b.slug));
writeFileSync(join(outDir, 'index.json'), JSON.stringify(index, null, 2) + '\n');
console.log(`build-skill: ${index.length} styles → skills/weft/references/`);
